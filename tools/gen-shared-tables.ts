// --- C# ScpiCommands ---
let csScpi = `// <auto-generated by tools/gen-shared-tables.ts />
namespace InstrumentComponents.Classes;

internal static class ScpiCommands
{
`;

for (const [key, base] of Object.entries(optionalRange)) {
  const name = snakeToPascal(key);
  csScpi += `    public static string ${name}(double? range) =>
        range is { } r ? $"${base} {r}" : "${base}";

`;
}

for (const key of configureSections) {
  const conf = scpi[key] as Record<string, string>;
  csScpi += emitConfigureFn(key, conf).cs + "\n\n";
}

for (const [key, tmpl] of Object.entries(templates)) {
  const name = snakeToPascal(key);
  const args = templateArgs(tmpl);
  // Special-case output enable: take bool, map to ON/OFF
  if (key === "psu_output_enable") {
    csScpi += `    public static string PsuOutputEnable(uint channel, bool enabled) => $":OUTP{channel} {(enabled ? "ON" : "OFF")}";\n`;
    continue;
  }
  if (key === "fgen_output_enable") {
    csScpi += `    public static string FgenOutputEnable(bool enabled) => $":OUTP {(enabled ? "ON" : "OFF")}";\n`;
    continue;
  }
  const csParams = args.map((a) => `${csArgType(a)} ${snakeToCamel(a)}`).join(", ");
  let interp = tmpl;
  for (const a of args) {
    interp = interp.replaceAll(`{${a}}`, `{${snakeToCamel(a)}}`);
  }
  if (interp.includes('"')) {
    // Prefer concatenation when the SCPI template embeds quotes
    const parts = interp.split(/(\{[a-zA-Z][a-zA-Z0-9]*\})/);
    const expr = parts.map((p) => {
      if (/^\{[a-zA-Z][a-zA-Z0-9]*\}$/.test(p)) return p.slice(1, -1);
      return JSON.stringify(p);
    }).join(" + ");
    csScpi += `    public static string ${name}(${csParams}) => ${expr};\n`;
  } else {
    csScpi += `    public static string ${name}(${csParams}) => $"${interp}";\n`;
  }
}

csScpi += "\n";
for (const [key, value] of Object.entries(consts)) {
  csScpi += `    public const string ${snakeToPascal(key)} = "${value}";\n`;
}
csScpi += "}\n";

