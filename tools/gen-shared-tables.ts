// Templates: extract placeholders
function templateArgs(tmpl: string): string[] {
  const args: string[] = [];
  const re = /\{([a-z0-9_]+)\}/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(tmpl))) {
    if (!args.includes(m[1])) args.push(m[1]);
  }
  return args;
}

function rustArgType(name: string): string {
  if (name === "channel" || name === "ch1" || name === "ch2" || name === "count") {
    return "u32";
  }
  if (name === "enabled") return "bool";
  if (
    name === "state" || name === "scpi_name" || name === "source" ||
    name === "slope" || name === "coupling" || name === "unit"
  ) {
    return "&str";
  }
  return "f64";
}

function csArgType(name: string): string {
  if (name === "channel" || name === "ch1" || name === "ch2" || name === "count") {
    return "uint";
  }
  if (name === "enabled") return "bool";
  if (
    name === "state" || name === "scpi_name" || name === "source" ||
    name === "slope" || name === "coupling" || name === "unit"
  ) {
    return "string";
  }
  return "double";
}

function emitConfigureFn(
  key: string,
  conf: Record<string, string>,
): { rust: string; cs: string } {
  const rustName = key;
  const csName = snakeToPascal(key);
  const withRr = conf.with_range_resolution!
    .replace("{range}", "{r}")
    .replace("{resolution}", "{res}");
  const withR = conf.with_range!.replace("{range}", "{r}");
  const withRes = conf.with_resolution!.replace("{resolution}", "{res}");
  const rust = `pub fn ${rustName}(range: Option<f64>, resolution: Option<f64>) -> String {
    match (range, resolution) {
        (Some(r), Some(res)) => format!("${withRr}"),
        (Some(r), None) => format!("${withR}"),
        (None, Some(res)) => format!("${withRes}"),
        (None, None) => "${conf.base}".into(),
    }
}`;
  const cs = `    public static string ${csName}(double? range, double? resolution) => (range, resolution) switch
    {
        ({ } r, { } res) => $"${withRr}",
        ({ } r, null) => $"${withR}",
        (null, { } res) => $"${withRes}",
        _ => "${conf.base}",
    };`;
  return { rust, cs };
}

for (const [key, tmpl] of Object.entries(templates)) {
  if (key.includes("output_enable")) {
    // special: bool enabled → ON/OFF state string in callers; keep template with {state}
  }
  const args = templateArgs(tmpl);
  const rustParams = args.map((a) => `${a}: ${rustArgType(a)}`).join(", ");
  const rustTmpl = tmpl.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  rustScpi += `pub fn ${key}(${rustParams}) -> String {
    format!("${rustTmpl}")
}

`;
}

for (const key of configureSections) {
  const conf = scpi[key] as Record<string, string>;
  rustScpi += emitConfigureFn(key, conf).rust + "\n\n";
}

